/// The llama.cpp release this crate builds.
pub const LLAMA_CPP_TAG: &str = env!("TROVE_LLAMA_CPP_TAG");

const MAX_SEQUENCES: usize = 16;

// More threads than this get slower on hybrid CPUs whose slow cores hold the fast ones back (DigUp's measurements).
const MAX_THREADS: usize = 8;

#[derive(Debug, Error)]
pub enum LlamaError {
    #[error("no llama.cpp compute backend could be loaded")]
    NoBackend,
    #[error("model path must be valid UTF-8 without NUL bytes: {0}")]
    InvalidPath(PathBuf),
    #[error("llama.cpp failed to load the model {0}")]
    LoadModel(PathBuf),
    #[error("llama.cpp failed to create a context")]
    CreateContext,
    #[error("input {0} is too long to tokenize")]
    InputTooLong(usize),
    #[error("llama.cpp failed to encode a batch (status {0})")]
    Encode(i32),
    #[error("llama.cpp returned no pooled embedding for input {0}")]
    MissingEmbedding(usize),
}

/// The devices llama.cpp may run a model on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Devices {
    /// llama.cpp's own choice: every GPU it found (Metal on macOS), else the CPU.
    Default,
    /// The CPU only, even when a GPU is present.
    Cpu,
}

/// A text embedding model on llama.cpp: mean-pooled, L2-normalised vectors. Freed on drop.
pub struct EmbeddingModel {
    model: NonNull<llama_model>,
    context: NonNull<llama_context>,
    batch: llama_batch,
    vocab: *const llama_vocab,
    max_tokens: usize,
    dims: usize,
}

// SAFETY: the model, context and batch are owned by this value and only used through `&mut self`, so one thread at a
// time; llama.cpp keeps no thread-local state for them.
unsafe impl Send for EmbeddingModel {}

impl EmbeddingModel {
    /// Loads the GGUF model at `path` on `devices`. Every input must fit `max_tokens`, which sizes the context, batch
    /// and micro-batch.
    pub fn load(path: &Path, max_tokens: u32, devices: Devices) -> Result<Self, LlamaError> {
        init_backend()?;

        let c_path = path
            .to_str()
            .and_then(|path| CString::new(path).ok())
            .ok_or_else(|| LlamaError::InvalidPath(path.to_path_buf()))?;

        // SAFETY: plain value struct from llama.cpp's defaults.
        let mut model_params = unsafe { llama_model_default_params() };
        // An empty device list leaves llama.cpp no GPU to pick. It copies the list while loading.
        let mut no_devices: [ggml_backend_dev_t; 1] = [std::ptr::null_mut()];
        if devices == Devices::Cpu {
            model_params.devices = no_devices.as_mut_ptr();
        }

        // SAFETY: `c_path` is a valid NUL-terminated string and `no_devices` outlives the call.
        let model =
            NonNull::new(unsafe { llama_model_load_from_file(c_path.as_ptr(), model_params) })
                .ok_or_else(|| LlamaError::LoadModel(path.to_path_buf()))?;

        let threads =
            thread::available_parallelism().map_or(1, |count| count.get().min(MAX_THREADS)) as i32;
        // SAFETY: plain value struct from llama.cpp's defaults.
        let mut params = unsafe { llama_context_default_params() };
        params.n_ctx = max_tokens;
        params.n_batch = max_tokens;
        params.n_ubatch = max_tokens;
        params.n_seq_max = MAX_SEQUENCES as u32;
        // Each input may use the whole context.
        params.kv_unified = true;
        params.embeddings = true;
        params.pooling_type = LLAMA_POOLING_TYPE_MEAN;
        params.n_threads = threads;
        params.n_threads_batch = threads;

        // SAFETY: `model` was just loaded and is freed only by this value or below.
        let Some(context) = NonNull::new(unsafe { llama_init_from_model(model.as_ptr(), params) })
        else {
            // SAFETY: nothing else holds `model`.
            unsafe { llama_model_free(model.as_ptr()) };
            return Err(LlamaError::CreateContext);
        };

        // SAFETY: `model` is valid; the batch is freed in `drop`.
        let (vocab, dims, batch) = unsafe {
            (
                llama_model_get_vocab(model.as_ptr()),
                llama_model_n_embd_out(model.as_ptr()) as usize,
                llama_batch_init(max_tokens as i32, 0, 1),
            )
        };

        Ok(Self {
            model,
            context,
            batch,
            vocab,
            max_tokens: max_tokens as usize,
            dims,
        })
    }

    /// One unit-length vector per text, in order. A text longer than the context is cut, keeping its end-of-sequence
    /// token, as the reference implementation (transformers) cuts it.
    pub fn embed(&mut self, texts: &[&str]) -> Result<Vec<Vec<f32>>, LlamaError> {
        let mut vectors = Vec::with_capacity(texts.len());
        let mut pending: Vec<Vec<llama_token>> = Vec::new();
        let mut pending_tokens = 0;

        for (index, text) in texts.iter().enumerate() {
            let tokens = self.tokenize(index, text)?;
            if pending.len() == MAX_SEQUENCES || pending_tokens + tokens.len() > self.max_tokens {
                vectors.extend(self.encode(&pending, vectors.len())?);
                pending.clear();
                pending_tokens = 0;
            }

            pending_tokens += tokens.len();
            pending.push(tokens);
        }

        if !pending.is_empty() {
            vectors.extend(self.encode(&pending, vectors.len())?);
        }

        Ok(vectors)
    }

    /// How many tokens `text` takes, special tokens included, before any cut to the context.
    pub fn count_tokens(&self, text: &str) -> Result<usize, LlamaError> {
        Ok(self.all_tokens(0, text)?.len())
    }

    fn tokenize(&self, index: usize, text: &str) -> Result<Vec<llama_token>, LlamaError> {
        let mut tokens = self.all_tokens(index, text)?;
        if tokens.len() > self.max_tokens {
            tokens.truncate(self.max_tokens - 1);
            // SAFETY: `vocab` belongs to the live model.
            tokens.push(unsafe { llama_vocab_eos(self.vocab) });
        }

        Ok(tokens)
    }

    fn all_tokens(&self, index: usize, text: &str) -> Result<Vec<llama_token>, LlamaError> {
        let length = i32::try_from(text.len()).map_err(|_| LlamaError::InputTooLong(index))?;
        let mut tokens: Vec<llama_token> = vec![0; text.len() + 2];
        let mut count = self.tokenize_into(text, length, &mut tokens);
        if count < 0 {
            tokens.resize(count.unsigned_abs() as usize, 0);
            count = self.tokenize_into(text, length, &mut tokens);
        }

        let count = usize::try_from(count).map_err(|_| LlamaError::InputTooLong(index))?;
        tokens.truncate(count);

        Ok(tokens)
    }

    fn tokenize_into(&self, text: &str, length: i32, tokens: &mut [llama_token]) -> i32 {
        // SAFETY: `text` is valid for `length` bytes and `tokens` for its length; llama.cpp reads and writes no further.
        unsafe {
            llama_tokenize(
                self.vocab,
                text.as_ptr().cast::<c_char>(),
                length,
                tokens.as_mut_ptr(),
                tokens.len() as i32,
                true,
                true,
            )
        }
    }

    /// Encodes the inputs as one batch, one sequence each. `first_index` numbers them in errors.
    fn encode(
        &mut self,
        inputs: &[Vec<llama_token>],
        first_index: usize,
    ) -> Result<Vec<Vec<f32>>, LlamaError> {
        let mut slot = 0;
        for (sequence, tokens) in inputs.iter().enumerate() {
            for (position, &token) in tokens.iter().enumerate() {
                // SAFETY: the batch was allocated for `max_tokens` tokens with one sequence id each, and `embed` never
                // puts more than `max_tokens` tokens in one batch.
                unsafe {
                    *self.batch.token.add(slot) = token;
                    *self.batch.pos.add(slot) = position as llama_pos;
                    *self.batch.n_seq_id.add(slot) = 1;
                    **self.batch.seq_id.add(slot) = sequence as llama_seq_id;
                    *self.batch.logits.add(slot) = 1;
                }
                slot += 1;
            }
        }
        self.batch.n_tokens = slot as i32;

        // SAFETY: the context is live and the batch holds `slot` initialised tokens.
        let status = unsafe { llama_encode(self.context.as_ptr(), self.batch) };
        if status != 0 {
            return Err(LlamaError::Encode(status));
        }

        (0..inputs.len())
            .map(|sequence| {
                // SAFETY: the context is live; a non-null result points at `dims` floats owned by the context.
                let pooled = unsafe {
                    llama_get_embeddings_seq(self.context.as_ptr(), sequence as llama_seq_id)
                };
                if pooled.is_null() {
                    return Err(LlamaError::MissingEmbedding(first_index + sequence));
                }

                // SAFETY: see above; copied out before the next call into the context.
                let pooled = unsafe { std::slice::from_raw_parts(pooled, self.dims) };
                Ok(normalised(pooled))
            })
            .collect()
    }
}

impl Drop for EmbeddingModel {
    fn drop(&mut self) {
        // SAFETY: all three were created in `load` and are freed only here.
        unsafe {
            llama_batch_free(self.batch);
            llama_free(self.context.as_ptr());
            llama_model_free(self.model.as_ptr());
        }
    }
}

fn normalised(vector: &[f32]) -> Vec<f32> {
    let norm = vector
        .iter()
        .map(|&value| f64::from(value).powi(2))
        .sum::<f64>()
        .sqrt();
    let scale = if norm > 0.0 { (1.0 / norm) as f32 } else { 0.0 };
    vector.iter().map(|&value| value * scale).collect()
}

/// Whether llama.cpp found a GPU, which `Devices::Default` then runs models on.
pub fn has_gpu() -> Result<bool, LlamaError> {
    init_backend()?;

    // SAFETY: the backends are initialised and every index below the count names a registered device.
    let has_gpu = unsafe {
        (0..ggml_backend_dev_count()).any(|index| {
            matches!(
                ggml_backend_dev_type(ggml_backend_dev_get(index)),
                GGML_BACKEND_DEVICE_TYPE_GPU | GGML_BACKEND_DEVICE_TYPE_IGPU
            )
        })
    };

    Ok(has_gpu)
}

/// llama.cpp's process-wide setup, run once.
fn init_backend() -> Result<(), LlamaError> {
    static READY: OnceLock<bool> = OnceLock::new();
    let ready = *READY.get_or_init(|| {
        // SAFETY: `log` matches the callback signature and needs no user data.
        unsafe {
            llama_log_set(Some(log), std::ptr::null_mut());
            #[cfg(not(target_os = "macos"))]
            ggml_backend_load_all();
            llama_backend_init();
            ggml_backend_dev_count() > 0
        }
    });

    if ready {
        Ok(())
    } else {
        Err(LlamaError::NoBackend)
    }
}

/// llama.cpp logs a lot while loading; only warnings and errors are kept, on stderr.
unsafe extern "C" fn log(level: ggml_log_level, text: *const c_char, _: *mut c_void) {
    // A continuation line belongs to the previous message and takes its level.
    // The enum's integer type differs between compilers, hence i64.
    static LAST_LEVEL: AtomicI64 = AtomicI64::new(GGML_LOG_LEVEL_INFO as i64);
    let level = if level == GGML_LOG_LEVEL_CONT {
        LAST_LEVEL.load(Ordering::Relaxed)
    } else {
        LAST_LEVEL.store(i64::from(level), Ordering::Relaxed);
        i64::from(level)
    };

    if level >= i64::from(GGML_LOG_LEVEL_WARN) && !text.is_null() {
        // SAFETY: llama.cpp passes a NUL-terminated message.
        eprint!("{}", unsafe { CStr::from_ptr(text) }.to_string_lossy());
    }
}
