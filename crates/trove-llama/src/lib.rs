pub const LLAMA_CPP_TAG: &str = env!("TROVE_LLAMA_CPP_TAG");

#[derive(Debug, Error)]
pub enum LlamaError {
    #[error("no llama.cpp compute backend could be loaded")]
    NoBackend,
    #[error("model path must be valid UTF-8 without NUL bytes: {0}")]
    InvalidPath(PathBuf),
    #[error("llama.cpp failed to load the model {0}")]
    LoadModel(PathBuf),
    #[error("llama.cpp failed to load the projector {0} for this model")]
    LoadProjector(PathBuf),
    #[error("no projector is loaded to embed images and audio")]
    NoProjector,
    #[error("the projector can't embed media input {0}: no encoder for its kind")]
    UnsupportedMedia(usize),
    #[error("media input {0} is not a readable file of its kind")]
    UnreadableMedia(usize),
    #[error("the projector failed to encode media input {0}")]
    EncodeMedia(usize),
    #[error("llama.cpp failed to create a context")]
    CreateContext,
    #[error("input {0} is too long to tokenize")]
    InputTooLong(usize),
    #[error("llama.cpp failed to encode a batch (status {0})")]
    Encode(i32),
    #[error("llama.cpp returned no pooled embedding for input {0}")]
    MissingEmbedding(usize),
    #[error("llama.cpp's CPU backend has no thread pools")]
    NoThreadpool,
    #[error("llama.cpp failed to start a thread pool")]
    CreateThreadpool,
    #[error("failed to lower the priority of the embedding thread")]
    LowerPriority(#[source] io::Error),
}

/// The devices llama.cpp may run a model on.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Devices {
    /// The first discrete GPU llama.cpp found (Metal on macOS, Vulkan elsewhere), else the CPU.
    Default,
    /// The CPU only, even when a GPU is present.
    Cpu,
}

/// A text embedding model on llama.cpp: mean-pooled, L2-normalised vectors. Freed on drop.
pub struct EmbeddingModel {
    model: NonNull<llama_model>,
    context: NonNull<llama_context>,
    batch: llama_batch,
    vocab: *const llama_vocab,
    max_tokens: usize,
    dims: usize,
    device: String,
    gpu: Option<ggml_backend_dev_t>,
    /// Loaded on request, for images and audio; freed before the model.
    projector: Option<Projector>,
    /// Started by the first low-priority call. ggml's CPU backend keeps a detached pool until its next graph, so the
    /// pool lives as long as the context.
    low_priority_pool: Option<Threadpool>,
}

// SAFETY: the model, context, batch and projector are owned by this value and only used through `&mut self`, so one
// thread at a time; llama.cpp and mtmd keep no thread-local state for them.
unsafe impl Send for EmbeddingModel {}

impl EmbeddingModel {
    /// Loads the GGUF model at `path` on `devices`. Every input must fit `max_tokens`, which sizes the context, batch
    /// and micro-batch.
    pub fn load(path: &Path, max_tokens: u32, devices: Devices) -> Result<Self, LlamaError> {
        init_backend()?;

        let c_path = path
            .to_str()
            .and_then(|path| CString::new(path).ok())
            .ok_or_else(|| LlamaError::InvalidPath(path.to_path_buf()))?;

        // SAFETY: plain value struct from llama.cpp's defaults.
        let mut model_params = unsafe { llama_model_default_params() };
        let gpu = match devices {
            Devices::Default => first_gpu(),
            Devices::Cpu => None,
        };
        // A null-terminated list of the one GPU, or empty, which leaves llama.cpp only the CPU. It copies the list
        // while loading.
        let mut device_list = [gpu.unwrap_or(std::ptr::null_mut()), std::ptr::null_mut()];
        model_params.devices = device_list.as_mut_ptr();

        // SAFETY: `c_path` is a valid NUL-terminated string and `device_list` outlives the call.
        let model =
            NonNull::new(unsafe { llama_model_load_from_file(c_path.as_ptr(), model_params) })
                .ok_or_else(|| LlamaError::LoadModel(path.to_path_buf()))?;

        let threads = Priority::Normal.threads() as i32;
        // SAFETY: plain value struct from llama.cpp's defaults.
        let mut params = unsafe { llama_context_default_params() };
        params.n_ctx = max_tokens;
        params.n_batch = max_tokens;
        params.n_ubatch = max_tokens;
        params.embeddings = true;
        params.pooling_type = LLAMA_POOLING_TYPE_MEAN;
        params.n_threads = threads;
        params.n_threads_batch = threads;

        // SAFETY: `model` was just loaded and is freed only by this value or below.
        let Some(context) = NonNull::new(unsafe { llama_init_from_model(model.as_ptr(), params) })
        else {
            // SAFETY: nothing else holds `model`.
            unsafe { llama_model_free(model.as_ptr()) };
            return Err(LlamaError::CreateContext);
        };

        // SAFETY: `model` is valid; the batch is freed in `drop`.
        let (vocab, dims, batch) = unsafe {
            (
                llama_model_get_vocab(model.as_ptr()),
                llama_model_n_embd_out(model.as_ptr()) as usize,
                llama_batch_init(max_tokens as i32, 0, 1),
            )
        };

        Ok(Self {
            model,
            context,
            batch,
            vocab,
            max_tokens: max_tokens as usize,
            dims,
            device: gpu.map_or_else(|| "CPU".to_owned(), device_description),
            gpu,
            projector: None,
            low_priority_pool: None,
        })
    }

    /// Loads the projector (mmproj) GGUF at `path`, which embeds images and audio into this model's vector space, on
    /// the model's device. Does nothing if one is loaded.
    pub fn load_projector(&mut self, path: &Path) -> Result<(), LlamaError> {
        if self.projector.is_none() {
            let threads = Priority::Normal.threads() as i32;
            self.projector = Some(Projector::load(path, self.model, self.gpu, threads)?);
        }

        Ok(())
    }

    pub fn has_projector(&self) -> bool {
        self.projector.is_some()
    }

    /// The sample rate `Media::AudioSamples` is taken at, once a projector with an audio encoder is loaded.
    pub fn audio_sample_rate(&self) -> Option<u32> {
        self.projector.as_ref()?.audio_sample_rate()
    }

    /// Decodes a WAV, MP3 or FLAC file to mono samples at `audio_sample_rate`, for embedding in windows.
    pub fn decode_audio(&self, bytes: &[u8]) -> Result<Vec<f32>, LlamaError> {
        let projector = self.projector.as_ref().ok_or(LlamaError::NoProjector)?;
        if projector.audio_sample_rate().is_none() {
            return Err(LlamaError::UnsupportedMedia(0));
        }
        projector.decode_audio(bytes)
    }

    /// One unit-length vector per image or audio clip, in order, in the same space as text vectors. Needs a loaded
    /// projector; each input must fit the context, as a text must.
    pub fn embed_media(
        &mut self,
        media: &[Media<'_>],
        priority: Priority,
    ) -> Result<Vec<Vec<f32>>, LlamaError> {
        if self.projector.is_none() {
            return Err(LlamaError::NoProjector);
        }

        self.at_priority(priority, |model| {
            let (llama, context, max_tokens, dims) =
                (model.model, model.context, model.max_tokens, model.dims);
            let projector = model.projector.as_mut().expect("checked above");
            media
                .iter()
                .enumerate()
                .map(|(index, &media)| {
                    projector.embed(llama, context, max_tokens, dims, media, index)
                })
                .collect()
        })
    }

    /// What the model runs on: the GPU's description from its driver, or `CPU`.
    pub fn device(&self) -> &str {
        &self.device
    }

    /// One unit-length vector per text, in order, computed at `priority`, which changes nothing in the vectors. A text
    /// longer than the context is cut, keeping its end-of-sequence token, as the reference implementation
    /// (transformers) cuts it.
    pub fn embed(
        &mut self,
        texts: &[&str],
        priority: Priority,
    ) -> Result<Vec<Vec<f32>>, LlamaError> {
        self.at_priority(priority, |model| model.embed_all(texts))
    }

    /// Runs `work` with the context's threads set for `priority`.
    fn at_priority<T: Send>(
        &mut self,
        priority: Priority,
        work: impl FnOnce(&mut Self) -> Result<T, LlamaError> + Send,
    ) -> Result<T, LlamaError> {
        let threads = priority.threads() as i32;
        // SAFETY: the context is live.
        unsafe { llama_set_n_threads(self.context.as_ptr(), threads, threads) };

        match priority {
            Priority::Normal => {
                // SAFETY: the context is live. Without a pool, ggml starts the workers of each graph from this thread.
                unsafe { llama_detach_threadpool(self.context.as_ptr()) };
                work(self)
            }
            // On a thread of its own, which takes the lowered priority with it when it ends.
            Priority::Low => thread::scope(|scope| {
                scope
                    .spawn(|| {
                        lower_this_thread()?;
                        let pool = match &self.low_priority_pool {
                            Some(pool) => pool.pool,
                            None => {
                                self.low_priority_pool
                                    .insert(Threadpool::low_priority(threads)?)
                                    .pool
                            }
                        };
                        // SAFETY: both are live, and the pool outlives the context.
                        unsafe {
                            llama_attach_threadpool(
                                self.context.as_ptr(),
                                pool.as_ptr(),
                                std::ptr::null_mut(),
                            );
                        }
                        work(self)
                    })
                    .join()
                    .unwrap_or_else(|payload| panic::resume_unwind(payload))
            }),
        }
    }

    // One text per batch: llama.cpp's numbers for a sequence change with what else shares its batch, and a note's
    // vectors must not depend on which other notes were embedded with it.
    fn embed_all(&mut self, texts: &[&str]) -> Result<Vec<Vec<f32>>, LlamaError> {
        texts
            .iter()
            .enumerate()
            .map(|(index, text)| {
                let tokens = self.tokenize(index, text)?;
                self.encode(&tokens, index)
            })
            .collect()
    }

    /// How many tokens `text` takes, special tokens included, before any cut to the context.
    pub fn count_tokens(&self, text: &str) -> Result<usize, LlamaError> {
        Ok(self.all_tokens(0, text)?.len())
    }

    fn tokenize(&self, index: usize, text: &str) -> Result<Vec<llama_token>, LlamaError> {
        let mut tokens = self.all_tokens(index, text)?;
        if tokens.len() > self.max_tokens {
            tokens.truncate(self.max_tokens - 1);
            // SAFETY: `vocab` belongs to the live model.
            tokens.push(unsafe { llama_vocab_eos(self.vocab) });
        }

        Ok(tokens)
    }

    fn all_tokens(&self, index: usize, text: &str) -> Result<Vec<llama_token>, LlamaError> {
        let length = i32::try_from(text.len()).map_err(|_| LlamaError::InputTooLong(index))?;
        let mut tokens: Vec<llama_token> = vec![0; text.len() + 2];
        let mut count = self.tokenize_into(text, length, &mut tokens);
        if count < 0 {
            tokens.resize(count.unsigned_abs() as usize, 0);
            count = self.tokenize_into(text, length, &mut tokens);
        }

        let count = usize::try_from(count).map_err(|_| LlamaError::InputTooLong(index))?;
        tokens.truncate(count);

        Ok(tokens)
    }

    fn tokenize_into(&self, text: &str, length: i32, tokens: &mut [llama_token]) -> i32 {
        // SAFETY: `text` is valid for `length` bytes and `tokens` for its length; llama.cpp reads and writes no further.
        unsafe {
            llama_tokenize(
                self.vocab,
                text.as_ptr().cast::<c_char>(),
                length,
                tokens.as_mut_ptr(),
                tokens.len() as i32,
                true,
                true,
            )
        }
    }

    /// Encodes one input as a batch of its own. `index` numbers it in errors.
    fn encode(&mut self, tokens: &[llama_token], index: usize) -> Result<Vec<f32>, LlamaError> {
        for (position, &token) in tokens.iter().enumerate() {
            // SAFETY: the batch was allocated for `max_tokens` tokens with one sequence id each, and `tokenize` never
            // returns more than `max_tokens` tokens.
            unsafe {
                *self.batch.token.add(position) = token;
                *self.batch.pos.add(position) = position as llama_pos;
                *self.batch.n_seq_id.add(position) = 1;
                **self.batch.seq_id.add(position) = 0;
                *self.batch.logits.add(position) = 1;
            }
        }
        self.batch.n_tokens = tokens.len() as i32;

        // SAFETY: the context is live and the batch holds `tokens.len()` initialised tokens.
        let status = unsafe { llama_encode(self.context.as_ptr(), self.batch) };
        if status != 0 {
            return Err(LlamaError::Encode(status));
        }

        // SAFETY: the context is live; a non-null result points at `dims` floats owned by the context.
        let pooled = unsafe { llama_get_embeddings_seq(self.context.as_ptr(), 0) };
        if pooled.is_null() {
            return Err(LlamaError::MissingEmbedding(index));
        }

        // SAFETY: see above; copied out before the next call into the context.
        let pooled = unsafe { std::slice::from_raw_parts(pooled, self.dims) };
        Ok(normalised(pooled))
    }
}

impl Drop for EmbeddingModel {
    fn drop(&mut self) {
        // The projector holds the model.
        self.projector = None;
        // SAFETY: all three were created in `load` and are freed only here, before `low_priority_pool` is.
        unsafe {
            llama_batch_free(self.batch);
            llama_free(self.context.as_ptr());
            llama_model_free(self.model.as_ptr());
        }
    }
}

fn normalised(vector: &[f32]) -> Vec<f32> {
    let norm = vector
        .iter()
        .map(|&value| f64::from(value).powi(2))
        .sum::<f64>()
        .sqrt();
    let scale = if norm > 0.0 { (1.0 / norm) as f32 } else { 0.0 };
    vector.iter().map(|&value| value * scale).collect()
}

/// Whether llama.cpp found a discrete GPU, which `Devices::Default` then runs models on.
pub fn has_gpu() -> Result<bool, LlamaError> {
    init_backend()?;
    Ok(first_gpu().is_some())
}

/// The GPU `Devices::Default` picks. Needs the backends initialised. Integrated Vulkan GPUs are skipped: on a Ryzen
/// iGPU (RADV) the same text embedded twice drifted to cosine 0.92, and indexed slower than the CPU. Metal reports
/// Apple GPUs as discrete.
fn first_gpu() -> Option<ggml_backend_dev_t> {
    // SAFETY: every index below the count names a registered device.
    unsafe {
        (0..ggml_backend_dev_count())
            .map(|index| ggml_backend_dev_get(index))
            .find(|&device| ggml_backend_dev_type(device) == GGML_BACKEND_DEVICE_TYPE_GPU)
    }
}

fn device_description(device: ggml_backend_dev_t) -> String {
    // SAFETY: `device` is registered, and its description is a NUL-terminated string it owns.
    unsafe { CStr::from_ptr(ggml_backend_dev_description(device)) }
        .to_string_lossy()
        .into_owned()
}

/// llama.cpp's process-wide setup, run once.
fn init_backend() -> Result<(), LlamaError> {
    static READY: OnceLock<bool> = OnceLock::new();
    let ready = *READY.get_or_init(|| {
        // SAFETY: `log` matches the callback signature and needs no user data.
        unsafe {
            llama_log_set(Some(log), std::ptr::null_mut());
            mtmd_helper_log_set(Some(log), std::ptr::null_mut());
            #[cfg(not(target_os = "macos"))]
            ggml_backend_load_all();
            llama_backend_init();
            ggml_backend_dev_count() > 0
        }
    });

    if ready {
        Ok(())
    } else {
        Err(LlamaError::NoBackend)
    }
}

/// llama.cpp logs a lot while loading, and warns about quirks of the pinned model's vocabulary on every load; only
/// errors are kept, on stderr.
unsafe extern "C" fn log(level: ggml_log_level, text: *const c_char, _: *mut c_void) {
    // A continuation line belongs to the previous message and takes its level.
    // The enum's integer type differs between compilers, hence i64.
    static LAST_LEVEL: AtomicI64 = AtomicI64::new(GGML_LOG_LEVEL_INFO as i64);
    let level = if level == GGML_LOG_LEVEL_CONT {
        LAST_LEVEL.load(Ordering::Relaxed)
    } else {
        LAST_LEVEL.store(i64::from(level), Ordering::Relaxed);
        i64::from(level)
    };

    if level >= i64::from(GGML_LOG_LEVEL_ERROR) && !text.is_null() {
        // SAFETY: llama.cpp passes a NUL-terminated message.
        eprint!("{}", unsafe { CStr::from_ptr(text) }.to_string_lossy());
    }
}
